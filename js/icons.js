/** Replace the content of every [data-icon] element with its SVG icon (keeps a label in data-label). */
export function applyIcons(root = document) {
  root.querySelectorAll('[data-icon]').forEach((el) => {
    const label = el.dataset.label ? `<span>${el.dataset.label}</span>` : '';
    el.innerHTML = icon(el.dataset.icon, +el.dataset.size || 22) + label;
  });
}
